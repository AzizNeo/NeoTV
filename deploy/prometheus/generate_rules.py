"""Writes neotv.rules.yml — SLO recording rules, burn-rate alerts and operational alerts.

    python deploy/prometheus/generate_rules.py      (CI fails if the committed file is stale)

The recording rules are mechanical (three SLIs x four windows), so they come from one table here
instead of being copied by hand. Thresholds follow the Google SRE Workbook's multi-window,
multi-burn-rate alerts: page when the error budget burns 14.4x too fast over both 1 h and 5 m
(2 % of a 30-day budget in an hour), open a ticket at 6x over both 6 h and 30 m.
"""

from __future__ import annotations

import sys
from pathlib import Path

OUT = Path(__file__).with_name("neotv.rules.yml")

# API traffic the SLOs speak about: not probes, not telemetry, not the media proxy (its speed and
# errors are mostly the origin's; it has its own alert below).
API = 'endpoint!~"kernel_health\\\\..*|kernel_metrics\\\\..*|kernel\\\\.client_events|playback\\\\.proxy"'
WINDOWS = ("5m", "30m", "1h", "6h")

# name: (objective, bad-events ratio over a window — WINDOW is replaced by 5m, 30m, …)
SLIS = {
    "availability": (
        0.995,
        'sum(rate(neotv_http_requests_total{status=~"5..",' + API + "}[WINDOW]))"
        " / sum(rate(neotv_http_requests_total{" + API + "}[WINDOW]))",
    ),
    "latency": (
        0.99,
        '1 - sum(rate(neotv_http_request_seconds_bucket{le="1.0",' + API + "}[WINDOW]))"
        " / sum(rate(neotv_http_request_seconds_count{" + API + "}[WINDOW]))",
    ),
    "playback_start": (
        0.95,
        '1 - sum(rate(neotv_playback_startup_seconds_bucket{le="3.0"}[WINDOW]))'
        " / sum(rate(neotv_playback_startup_seconds_count[WINDOW]))",
    ),
}
WHAT = {
    "availability": "API requests answered without a server error (5xx)",
    "latency": "API requests answered within 1 s",
    "playback_start": "streams showing their first frame within 3 s",
}
# (severity, burn rate, long window, short window, for)
BURNS = (("page", 14.4, "1h", "5m", "2m"), ("ticket", 6, "6h", "30m", "15m"))


def rule_file() -> str:
    lines = [
        "# GENERATED by deploy/prometheus/generate_rules.py — edit the generator, not this file.",
        "# Unit tests: neotv.rules.test.yml (promtool test rules). Runbooks: docs/runbooks.md.",
        "groups:",
        "  - name: neotv-sli",
        "    interval: 30s",
        "    rules:",
    ]
    for sli, (_, expr) in SLIS.items():
        for w in WINDOWS:
            lines += [
                f"      - record: neotv:sli_{sli}_errors:ratio_rate{w}",
                f"        expr: {expr.replace('WINDOW', w)}",
            ]
    lines += ["", "  - name: neotv-slo-burn", "    rules:"]
    for sli, (objective, _) in SLIS.items():
        budget = round(1 - objective, 6)
        name = "".join(part.title() for part in sli.split("_"))
        for severity, burn, long_w, short_w, hold in BURNS:
            threshold = round(burn * budget, 6)
            lines += [
                f"      - alert: NeoTV{name}BudgetBurn{severity.title()}",
                f"        expr: neotv:sli_{sli}_errors:ratio_rate{long_w} > {threshold}"
                f" and neotv:sli_{sli}_errors:ratio_rate{short_w} > {threshold}",
                f"        for: {hold}",
                "        labels:",
                f"          severity: {severity}",
                f"          slo: {sli}",
                "        annotations:",
                f'          summary: "{WHAT[sli]}: error budget burning {burn}x too fast"',
                f'          description: "Objective {objective:.1%}. Bad-event ratio over {long_w}:'
                f' {{{{ $value | humanizePercentage }}}} (alert at {threshold:.2%})."',
                f"          runbook_url: docs/runbooks.md#slo-{sli.replace('_', '-')}",
            ]
    lines += [
        "",
        "  - name: neotv-operations",
        "    rules:",
        "      - alert: NeoTVApiDown",
        '        expr: up{job="neotv-api"} == 0',
        "        for: 2m",
        "        labels: {severity: page}",
        "        annotations:",
        '          summary: "Prometheus cannot scrape the NeoTV API"',
        "          runbook_url: docs/runbooks.md#api-down",
        "      - alert: NeoTVOutboxLagging",
        "        expr: max(neotv_outbox_lag_seconds) > 300",
        "        for: 10m",
        "        labels: {severity: ticket}",
        "        annotations:",
        '          summary: "Domain events wait over 5 minutes for delivery (workers down or a consumer failing)"',
        "          runbook_url: docs/runbooks.md#outbox-lagging",
        "      - alert: NeoTVDeadLetters",
        "        expr: max(neotv_outbox_dead_letters) > 0",
        "        for: 15m",
        "        labels: {severity: ticket}",
        "        annotations:",
        '          summary: "Event deliveries that gave up and wait for a human: {{ $value }}"',
        "          runbook_url: docs/runbooks.md#dead-letters",
        "      - alert: NeoTVCircuitOpen",
        "        expr: max by (name) (neotv_circuit_open) == 1",
        "        for: 5m",
        "        labels: {severity: ticket}",
        "        annotations:",
        '          summary: "Circuit {{ $labels.name }} has been open for 5 minutes"',
        "          runbook_url: docs/runbooks.md#circuit-open",
        "      - alert: NeoTVOriginFailures",
        "        expr: >-",
        "          sum(rate(neotv_playback_proxy_errors_total[10m]))",
        '          / sum(rate(neotv_http_requests_total{endpoint="playback.proxy"}[10m])) > 0.05',
        "        for: 10m",
        "        labels: {severity: ticket}",
        "        annotations:",
        '          summary: "Over 5% of media requests fail at the origin ({{ $value | humanizePercentage }})"',
        "          runbook_url: docs/runbooks.md#origin-failures",
        "      - alert: NeoTVBrowserErrors",
        "        expr: sum(rate(neotv_client_errors_total[15m])) * 60 > 5",
        "        for: 15m",
        "        labels: {severity: ticket}",
        "        annotations:",
        '          summary: "Viewers\' browsers report {{ $value | humanize }} uncaught errors per minute"',
        "          runbook_url: docs/runbooks.md#browser-errors",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    content = rule_file()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print(f"{OUT.name} is stale: run python deploy/prometheus/generate_rules.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
