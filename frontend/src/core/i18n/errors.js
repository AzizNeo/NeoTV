const known = errorMessages.tables.tr;

export function messageFor(code, fallback) {
  if (code && known.has(code)) return translate(errorMessages, code);
  if (code?.startsWith('HTTP_5')) return translate(errorMessages, 'INTERNAL_ERROR');
  return fallback && fallback !== code ? fallback : translate(errorMessages, 'FALLBACK');
}
