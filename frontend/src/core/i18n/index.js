export function messageFor(code, fallback) {
  if (code && ERRORS[code]) return ERRORS[code];
  if (code?.startsWith('HTTP_5')) return ERRORS.INTERNAL_ERROR;
  return fallback && fallback !== code ? fallback : 'İşlem tamamlanamadı.';
}
